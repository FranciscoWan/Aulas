# Programação imperativa se concentra em alterar o estado do programa através de uma sequência de comandos.
# As instruções são executadas de cima para baixo a menos que alteradas por estruturas de controle, como loops ou condicionais.
# Foca em como fazer
# O código é lido de cima para baixo, a menos que existam estruturas de controle.

lista_numeros = [1,2,3,4,5,6,7,8]

for i in lista_numeros:
    if i % 2 == 0:
        print(f"O número {i} é par")

print("Programa encerrado")

